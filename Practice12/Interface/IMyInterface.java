public interface IMyInterface 
{
	//This is an interface now
	//Interface by default public
	//We can't create any object of an interface, but we can use object reference 
	//Interface doesn't have any constructor 
	//Interface stores the abstract methods 
	//Methods are by default abstract and public 
	//Attributes are by default	public, static and final
	public abstract void show1();
	public void show2();
}